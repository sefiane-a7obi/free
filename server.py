def decompress_if_gzip(data: bytes) -> bytes:
    if len(data) >= 2 and data[:2] == b"\x1f\x8b":
        try:
            return gzip.decompress(data)
        except Exception as e:
            print(f"[Warning] Failed to gzip-decompress: {e}")
            return data
    return data



import re

def process_il2cpp_pure_python(lib_path: Path, meta_path: Path, out_dir: Path) -> dict:
    with open(meta_path, "rb") as f:
        meta_bytes = f.read()

    magic = meta_bytes[:4] if len(meta_bytes) >= 4 else b""
    is_valid_magic = (magic == b"\xaf\x1b\xb1\xfa")
    version = int.from_bytes(meta_bytes[4:8], "little") if len(meta_bytes) >= 8 and is_valid_magic else 0

    # Extract readable string literals safely from metadata
    strings_found = []
    ascii_strings = re.findall(rb"[\x20-\x7e]{4,80}", meta_bytes[:600000])
    seen = set()
    for s in ascii_strings:
        try:
            st = s.decode("utf-8", errors="ignore").strip()
            if st and st not in seen and len(st) >= 4:
                seen.add(st)
                strings_found.append({"value": st, "length": len(st)})
                if len(strings_found) >= 1000:
                    break
        except Exception:
            pass

    # Generate dump.cs
    dump_cs_path = out_dir / "dump.cs"
    with open(dump_cs_path, "w", encoding="utf-8") as f:
        f.write("// ================================================================\n")
        f.write("// Dump generated by Tenzo Il2Cpp Dumper Clone (Pure Python Engine)\n")
        f.write(f"// Metadata Version: {version if is_valid_magic else 'Encrypted/Custom'}\n")
        f.write(f"// Binary: {lib_path.name} ({os.path.getsize(lib_path):,} bytes)\n")
        f.write(f"// Metadata: {meta_path.name} ({len(meta_bytes):,} bytes)\n")
        f.write(f"// Total Strings Extracted: {len(strings_found)}\n")
        f.write("// ================================================================\n\n")
        f.write("namespace Il2CppDump\n{\n")
        f.write("    public static class DumpInfo\n    {\n")
        f.write(f"        public const int MetadataVersion = {version};\n")
        f.write(f"        public const string SourceBinary = \"{lib_path.name}\";\n")
        f.write(f"        public const int ExtractedStringsCount = {len(strings_found)};\n")
        f.write("    }\n}\n")

    # Generate stringliteral.json
    with open(out_dir / "stringliteral.json", "w", encoding="utf-8") as f:
        json.dump(strings_found, f, indent=2, ensure_ascii=False)

    # Generate script.json
    with open(out_dir / "script.json", "w", encoding="utf-8") as f:
        json.dump({
            "ScriptMethod": [],
            "ScriptMetadata": [{"Address": 0, "Name": "MetadataRegistration", "Signature": "void*"}],
            "Addresses": []
        }, f, indent=2)

    # Generate il2cpp.h
    with open(out_dir / "il2cpp.h", "w", encoding="utf-8") as f:
        f.write("// IL2CPP C++ Definitions\n#pragma once\n#include <stdint.h>\n")

    # Copy metadata
    shutil.copy2(meta_path, out_dir / "global-metadata.dat")

    return {
        "version": version,
        "valid": is_valid_magic,
        "strings_count": len(strings_found)
    }


def run_dump_worker(job_id: str):
    job = jobs.get(job_id)
    if not job:
        return

    job_dir = Path(job["job_dir"])
    lib_path = job_dir / "libil2cpp.so"
    meta_path = job_dir / "global-metadata.dat"
    out_dir = job_dir / "output"
    out_dir.mkdir(parents=True, exist_ok=True)

    try:
        job["status"] = "processing"
        job["step"] = "Checking metadata & binary format..."
        time.sleep(0.3)

        if not lib_path.exists() or not meta_path.exists():
            raise RuntimeError("Missing uploaded files.")

        # Check metadata header
        with open(meta_path, "rb") as f:
            header = f.read(8)

        magic = header[:4] if len(header) >= 4 else b""
        if magic == b"\xaf\x1b\xb1\xfa":
            version = int.from_bytes(header[4:8], "little") if len(header) >= 8 else 0
            job["step"] = f"Valid Unity metadata (v{version}) detected. Starting official Il2CppDumper..."
        else:
            job["step"] = "Custom/Encrypted metadata detected. Starting Il2CppDumper..."

        time.sleep(0.5)

        dumper_to_use = SEFIANE_DUMPER
        if not dumper_to_use.exists():
            raise RuntimeError("SEFIANE STORE Dumper executable not found.")

        job["step"] = "Decompiling with SEFIANE STORE Dumper engine..."

        # Ensure out_dir ends with trailing slash
        out_str = str(out_dir)
        if not out_str.endswith(os.sep):
            out_str += os.sep

        if sys.platform != "win32" and str(dumper_to_use).endswith(".exe"):
            cmd = ["wine", str(dumper_to_use), str(lib_path), str(meta_path), out_str]
        else:
            cmd = [str(dumper_to_use), str(lib_path), str(meta_path), out_str]

        proc = subprocess.Popen(
            cmd,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            cwd=str(dumper_to_use.parent),
        )

        try:
            stdout, stderr = proc.communicate(input="\n\n\n\n\n", timeout=300)
        except subprocess.TimeoutExpired:
            proc.kill()
            raise RuntimeError("Decompilation timed out after 5 minutes.")

        # Check for dump.cs (either inside out_dir or concatenated)
        dump_cs = out_dir / "dump.cs"
        if not dump_cs.exists():
            alt_dump = Path(str(out_dir) + "dump.cs")
            if alt_dump.exists():
                shutil.move(str(alt_dump), str(dump_cs))

        if not dump_cs.exists() or dump_cs.stat().st_size < 1000:
            lines = [l.strip() for l in (stdout + "\n" + stderr).splitlines() if l.strip()]
            err_line = ""
            for l in lines:
                if "Unhandled exception" in l or "System." in l:
                    err_line = l
                    break
            if not err_line and lines:
                err_line = lines[-1]
            if not err_line:
                err_line = "SEFIANE STORE Dumper failed to generate dump.cs"
            raise RuntimeError(f"Decompiler Error: {err_line}")

        job["step"] = f"Dump completed ({dump_cs.stat().st_size // (1024*1024):,} MB). Packaging archive..."
        time.sleep(0.3)

        # Copy original/decrypted metadata into output
        shutil.copy2(meta_path, out_dir / "global-metadata.dat")

        # Copy scripts if available in bin
        for script_name in ["ida.py", "ghidra.py", "config.json"]:
            src = dumper_to_use.parent / script_name
            dst = out_dir / script_name
            if src.exists() and not dst.exists():
                shutil.copy2(src, dst)

        # Create zip archive
        job["step"] = "Creating final zip package..."
        zip_path = job_dir / "SEFIANE_STORE_il2cpp_dump.zip"
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zipf:
            for root, _, files in os.walk(out_dir):
                for file in files:
                    file_path = Path(root) / file
                    arcname = file_path.relative_to(out_dir)
                    zipf.write(file_path, arcname)

        job["archive_path"] = str(zip_path)
        job["status"] = "completed"
        job["step"] = f"Dump completed successfully ({zip_path.stat().st_size // (1024*1024):,} MB)."

    except Exception as e:
        job["status"] = "error"
        job["error"] = str(e)


async def background_queue_runner():
    while True:
        job_id = await queue.get()
        try:
            # Update queue positions for remaining queued jobs
            queued_jobs = [j for j in jobs.values() if j["status"] == "queued"]
            for idx, j in enumerate(queued_jobs):
                j["position"] = idx + 1
                j["queue_length"] = len(queued_jobs)

            # Run in worker thread
            await asyncio.to_thread(run_dump_worker, job_id)
        except Exception as e:
            print(f"[Error in queue runner]: {e}")
        finally:
            queue.task_done()



@app.post("/api/queue/submit")
async def queue_submit(
    libil2cpp: UploadFile = File(...),
    metadata: UploadFile = File(...),
    fingerprint: str = Form(""),
):
    job_id = str(uuid.uuid4())
    job_dir = JOBS_DIR / job_id
    job_dir.mkdir(parents=True, exist_ok=True)

    lib_raw = await libil2cpp.read()
    meta_raw = await metadata.read()

    lib_decomp = decompress_if_gzip(lib_raw)
    meta_decomp = decompress_if_gzip(meta_raw)

    lib_file = job_dir / "libil2cpp.so"
    meta_file = job_dir / "global-metadata.dat"

    with open(lib_file, "wb") as f:
        f.write(lib_decomp)

    with open(meta_file, "wb") as f:
        f.write(meta_decomp)

    job_info = {
        "job_id": job_id,
        "job_dir": str(job_dir),
        "status": "queued",
        "position": queue.qsize() + 1,
        "queue_length": queue.qsize() + 1,
        "step": "Queued",
        "error": None,
        "archive_path": None,
        "fingerprint": fingerprint,
        "created_at": time.time(),
    }
    jobs[job_id] = job_info

    await queue.put(job_id)

    return {
        "job_id": job_id,
        "status": "queued",
        "position": job_info["position"],
        "queue_length": job_info["queue_length"],
        "step": "Queued",
    }


@app.get("/api/queue/status/{job_id}")
async def queue_status(job_id: str):
    job = jobs.get(job_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found or already purged.")

    queued_list = [j for j in jobs.values() if j["status"] == "queued"]
    pos = 1
    for idx, j in enumerate(queued_list):
        if j["job_id"] == job_id:
            pos = idx + 1
            break

    return {
        "job_id": job_id,
        "status": job["status"],
        "position": pos,
        "queue_length": max(1, len(queued_list)),
        "step": job.get("step", ""),
        "error": job.get("error"),
    }


@app.get("/api/queue/download/{job_id}")
async def queue_download(job_id: str):
    job = jobs.get(job_id)
    if not job or not job.get("archive_path"):
        raise HTTPException(status_code=404, detail="Dump archive not ready or job not found.")

    archive_path = Path(job["archive_path"])
    if not archive_path.exists():
        raise HTTPException(status_code=404, detail="Archive file missing on server.")

    return FileResponse(
        path=str(archive_path),
        media_type="application/zip",
        filename="SEFIANE_STORE_il2cpp_dump.zip",
    )


@app.post("/api/queue/confirm/{job_id}")
async def queue_confirm(job_id: str):
    job = jobs.get(job_id)
    if job:
        job_dir = Path(job["job_dir"])
        try:
            if job_dir.exists():
                shutil.rmtree(job_dir, ignore_errors=True)
            jobs.pop(job_id, None)
        except Exception as e:
            print(f"[Cleanup Error] {e}")
    return {"status": "ok"}


